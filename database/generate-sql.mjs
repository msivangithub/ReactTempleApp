/** SQL literal. Strings become N'...' and any non-ASCII character becomes NCHAR(n) so the file stays ASCII. */
function q(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  const parts = [];
  let buf = '';
  const flush = () => { if (buf) parts.push(`N'${buf.replace(/'/g, "''")}'`); buf = ''; };
  for (const ch of String(v)) {
    const cp = ch.codePointAt(0);
    if (cp >= 32 && cp < 127) { buf += ch; continue; }
    flush();
    if (cp > 0xffff) { const h = Math.floor((cp - 0x10000) / 0x400) + 0xd800; const l = ((cp - 0x10000) % 0x400) + 0xdc00; parts.push(`NCHAR(${h}) + NCHAR(${l})`); }
    else parts.push(`NCHAR(${cp})`);
  }
  flush();
  if (!parts.length) return "N''";
  return parts.length === 1 ? parts[0] : `(${parts.join(' + ')})`;
}
